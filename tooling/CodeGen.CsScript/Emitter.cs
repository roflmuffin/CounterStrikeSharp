using System.Text.Json;

namespace CodeGen.CsScript;

public static class Emitter
{

    private static readonly IReadOnlyDictionary<string, string> EntityClassOverrides = new Dictionary<string, string>(StringComparer.Ordinal)
    {
        ["Entity"] = "CBaseEntity", ["CSGrenadeProjectileBase"] = "CBaseCSGrenadeProjectile",
        ["CSPlantedC4"] = "CPlantedC4", ["CSHostage"] = "CHostage",
        ["CSRadarPoint"] = "CCSRadarElement", ["CSObservablePoint"] = "CCSObservableElement",
        ["CustomHudLayout"] = "CCSCustomHudLayout", ["CustomPlayerCamera"] = "CCSCustomPlayerCamera"
    };
    public static string EntityClass(string exportName) => EntityClassOverrides.GetValueOrDefault(exportName) ?? "C" + exportName;

    private static readonly HashSet<string> RenamedMembers = new(StringComparer.Ordinal)
    {
        "Entity.IsValid", "Entity.Remove", "BaseModelEntity.SetModel", "CSHostage.IsRescued",
        "CSPlayerController.IsBot", "CSPlayerPawn.IsScoped", "CSPlayerPawn.IsBuyMenuOpen"
    };
    private static string Hex(uint value) => $"0x{value:x8}";
    private static string Literal(string value) => JsonSerializer.Serialize(value, Json.Compact);
    private static string ShapeIdentity(Shape shape) => shape.Kind switch
    {
        "enum" => $"enum:{shape.EnumName}",
        "entity" => $"entity:{shape.EntityType}" + (shape.Absence is null ? "" : $"|{shape.Absence}"),
        _ => shape.Kind
    };
    private static string Type(Shape shape) => shape.Kind switch
    {
        "number" => "double", "string" => "string", "boolean" => "bool", "void" => "void",
        "enum" => shape.EnumName!, "entity" => EntityClass(shape.EntityType!) + (shape.Absence is null ? "" : "?"), _ => throw new InvalidDataException($"Unsupported emitted shape: {shape.Kind}")
    };
    private static string NativeKind(Shape shape) => shape.Kind switch
    {
        "number" or "enum" => "Number", "string" => "String", "boolean" => "Boolean", "void" => "Void",
        "entity" => shape.Absence switch
        {
            null => "Entity", "undefined" => "EntityOrUndefined", "null" => "EntityOrNull", "null|undefined" => "EntityOrNullOrUndefined",
            _ => throw new InvalidDataException($"Unsupported entity absence: {shape.Absence}")
        },
        _ => throw new InvalidDataException($"Unsupported native shape: {shape.Kind}")
    };

    public static uint NativeHash(string identity)
    {
        uint hash = 5381;
        foreach (var c in identity)
        {
            if (c > 127) throw new InvalidDataException("Native hash identities must be ASCII");
            hash = unchecked(hash * 33 ^ c);
        }
        return hash;
    }
    public static string MethodIdentity(string module, Receiver receiver, Method method) =>
        $"{module}:{receiver.Kind}:{receiver.ExportName}.{method.Member}(" +
        string.Join(',', method.Parameters.Select(p => ShapeIdentity(p.Shape) + (p.Optional ? "?" : ""))) +
        $")->{ShapeIdentity(method.Returns)}";

    private static IEnumerable<Method> BaseMethods(Manifest manifest, Receiver receiver) => receiver.Bases
        .SelectMany(name => manifest.Receivers.Where(r => r.ExportName == name))
        .SelectMany(parent => parent.Methods.Concat(BaseMethods(manifest, parent)));

    public static Output Emit(Manifest manifest)
    {
        var api = new List<string> { "// <auto-generated />", "#nullable enable", "using System;", "using CounterStrikeSharp.API.Core;", "namespace CounterStrikeSharp.API.Modules.CsScript;", "" };
        var entities = new List<string> { "// <auto-generated />", "#nullable enable", "using CounterStrikeSharp.API.Modules.CsScript;", "namespace CounterStrikeSharp.API.Core;", "" };
        foreach (var definition in manifest.Enums)
        {
            if (definition.Deprecated) api.Add("[Obsolete]");
            api.AddRange([$"public enum {definition.Name} : long", "{"]);
            api.AddRange(definition.Members.Select(m => $"    @{m.Name} = {m.Value}L,"));
            api.AddRange(["}", ""]);
        }
        var descriptors = new List<Descriptor>();
        var identities = new Dictionary<uint, string>();
        foreach (var receiver in manifest.Receivers)
        {
            var entity = receiver.Kind == "entity";
            var name = entity ? EntityClass(receiver.ExportName) : $"CsScript{receiver.ExportName}";
            var target = entity ? entities : api;
            if (entity) target.AddRange([$"public partial class {name}", "{"]);
            else target.AddRange([$"public sealed class {name}", "{", "    private readonly CsScriptRuntime runtime;",
                $"    internal {name}(CsScriptRuntime runtime) {{ this.runtime = runtime; }}"]);
            var emitted = new HashSet<string>(StringComparer.Ordinal);
            foreach (var method in receiver.Methods.Where(m => m.Supported))
            {
                var identity = MethodIdentity(manifest.Module, receiver, method);
                var id = NativeHash(identity);
                if (!identities.TryAdd(id, identity)) throw new InvalidDataException($"Method hash collision {Hex(id)}: {identities[id]} / {identity}");
                if (method.MaximumArgumentCount > 24) throw new InvalidDataException($"ScriptContext argument capacity exceeded: {identity}");
                descriptors.Add(new(id, identity, receiver, method));

                if (entity && method.DeclaringReceiver != receiver.ExportName) continue;
                var member = method.Member + (entity && RenamedMembers.Contains($"{receiver.ExportName}.{method.Member}") ? "Script" : "");
                for (var argc = method.MinimumArgumentCount; argc <= method.MaximumArgumentCount; argc++)
                {
                    var parameters = method.Parameters.Take(argc).ToArray();
                    var key = $"{member}({string.Join(',', parameters.Select(p => Type(p.Shape)))})";
                    if (!emitted.Add(key)) throw new InvalidDataException($"C# overload collision: {receiver.ExportName}.{key}");
                    if (method.Documentation.Length > 0)
                    {
                        target.Add("    /// <summary>");
                        target.AddRange(method.Documentation.Split('\n').Select(l => "    /// " + l.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;")));
                        target.Add("    /// </summary>");
                    }
                    var hidesBase = entity && BaseMethods(manifest, receiver).Any(m => m.Supported && m.Member == method.Member &&
                        m.Parameters.Count >= argc && m.MinimumArgumentCount <= argc &&
                        m.Parameters.Take(argc).Select(p => Type(p.Shape)).SequenceEqual(parameters.Select(p => Type(p.Shape))));
                    target.Add($"    public {(hidesBase ? "new " : "")}{Type(method.Returns)} @{member}({string.Join(", ", parameters.Select(p => $"{Type(p.Shape)} @{p.Name}"))})");
                    target.Add("    {");
                    target.Add($"        using var call = {(entity ? "CsScriptRuntime.Shared" : "runtime")}.BeginInvoke({Hex(id)}u, {(entity ? "EntityHandle.Raw" : "uint.MaxValue")});");
                    target.AddRange(parameters.Select(p => p.Shape.Kind == "entity"
                        ? $"        call.PushEntity(@{p.Name}, {(p.Shape.Absence is null ? "false" : "true")});"
                        : $"        call.Push({(p.Shape.Kind == "enum" ? "(double)" : "")}@{p.Name});"));
                    target.Add("        call.Invoke();");
                    if (method.Returns.Kind != "void")
                    {
                        var result = method.Returns.Kind switch
                        {
                            "entity" => $"call.{(method.Returns.Absence is null ? "EntityResult" : "OptionalEntityResult")}<{EntityClass(method.Returns.EntityType!)}>()",
                            "string" => "call.StringResult()",
                            _ => $"call.Result<{(method.Returns.Kind == "enum" ? "double" : Type(method.Returns))}>()"
                        };
                        target.Add($"        return {(method.Returns.Kind == "enum" ? $"({Type(method.Returns)})" : "")}{result};");
                    }
                    target.Add("    }");
                }
            }
            target.AddRange(["}", ""]);
        }
        var native = new List<string>
        {
            "// <auto-generated />", "#pragma once", "#include <array>", "#include <cstdint>",
            "namespace counterstrikesharp::cs_script {"
        };
        native.AddRange(["enum class ValueKind { Void, Number, Boolean, String, Entity, EntityOrUndefined, EntityOrNull, EntityOrNullOrUndefined };",
            "struct MethodDescriptor { uint32_t id; const char* receiver; const char* member; bool entity; int minimumArguments; int maximumArguments; std::array<ValueKind, 24> parameters; ValueKind result; };",
            $"inline constexpr std::array<MethodDescriptor, {descriptors.Count}> Descriptors = {{{{"]);
        native.AddRange(descriptors.Select(d => $"    {{{Hex(d.Id)}u, {Literal(d.Receiver.ExportName)}, {Literal(d.Method.Member)}, {(d.Receiver.Kind == "entity" ? "true" : "false")}, {d.Method.MinimumArgumentCount}, {d.Method.MaximumArgumentCount}, {{{string.Join(", ", d.Method.Parameters.Select(p => $"ValueKind::{NativeKind(p.Shape)}"))}}}, ValueKind::{NativeKind(d.Method.Returns)}}},"));
        native.AddRange(["}};", "}"]);
        return new(string.Join('\n', api).TrimEnd() + '\n', string.Join('\n', entities) + '\n', string.Join('\n', native) + '\n', descriptors);
    }
}
