using System.Text;
using System.Text.RegularExpressions;

namespace CodeGen.Natives.Scripts;

public partial class Generators
{
    // Where Engine Features are declared: the native catalog and the managed catalog. Every quoted
    // "cssharp.<area>/<name>" literal outside a // comment in these files is an Engine Feature name.
    private static readonly string[] EngineFeatureSources =
    {
        "src/core/engine_features.h",
        "src/core/engine_features.cpp",
        "managed/CounterStrikeSharp.API/Core/Bindings/ManagedEngineFeatures.cs",
    };

    private static readonly Regex EngineFeatureName = new("\"(cssharp\\.[a-z0-9-]+/[a-z0-9-]+)\"");

    /// <summary>
    /// Generates the <c>EngineFeature</c> enum and <c>EngineFeatureNames</c> from the Engine Feature names declared in
    /// code. Re-runnable: the output depends only on the set of names. Each value is a hash of the name, so it never
    /// changes when other names are added (plugins compile the value in; names are never renamed or reused).
    /// </summary>
    public static void GenerateEngineFeatures()
    {
        var root = Helpers.GetRootDirectory();
        var names = EngineFeatureSources
            .SelectMany(source => File.ReadAllLines(Path.Join(root, source)))
            .Select(line => line.Split("//")[0])
            .SelectMany(line => EngineFeatureName.Matches(line).Select(match => match.Groups[1].Value))
            .Distinct()
            .OrderBy(name => name, StringComparer.Ordinal)
            .ToList();

        var members = names.Select(name => (Name: name, Member: EngineFeatureMemberName(name), Value: EngineFeatureValue(name)))
            .ToList();
        foreach (var clash in members.GroupBy(m => m.Member).Where(g => g.Count() > 1)
                     .Concat(members.GroupBy(m => m.Value.ToString()).Where(g => g.Count() > 1)))
        {
            throw new InvalidOperationException(
                $"Engine Feature names {string.Join(", ", clash.Select(m => m.Name))} map to the same enum member or value");
        }

        var output = new StringBuilder();
        output.Append("""
                      // <auto-generated>
                      // Generated by tooling/CodeGen.Natives from the Engine Feature catalogs (src/core/engine_features.*,
                      // Core/Bindings/ManagedEngineFeatures.cs). Do not edit; rerun:
                      //   dotnet run --project tooling/CodeGen.Natives -- engine-features
                      // </auto-generated>

                      namespace CounterStrikeSharp.API.Core;

                      /// <summary>
                      /// Engine Features by name, for autocomplete and typo safety. The string name is the identity
                      /// (see <see cref="EngineFeatureNames"/>); each value is a stable hash of the name.
                      /// </summary>
                      public enum EngineFeature
                      {

                      """);
        output.Append(string.Join("\n", members.Select(m => $"    /// <summary><c>{m.Name}</c></summary>\n    {m.Member} = {m.Value},\n")));

        output.Append("""
                      }

                      /// <summary>The stable string names of the <see cref="EngineFeature"/> values.</summary>
                      public static class EngineFeatureNames
                      {

                      """);
        foreach (var (name, member, _) in members)
        {
            output.Append($"    /// <summary><c>{name}</c></summary>\n");
            output.Append($"    public const string {member} = \"{name}\";\n\n");
        }

        output.Append("""
                          /// <summary>The name of an Engine Feature value; null for a value this version does not know.</summary>
                          public static string? GetName(this EngineFeature feature) => feature switch
                          {

                      """);
        foreach (var (_, member, _) in members)
        {
            output.Append($"        EngineFeature.{member} => {member},\n");
        }

        output.Append("""
                              _ => null,
                          };
                      }

                      """);

        File.WriteAllText(
            Path.Join(root, "managed/CounterStrikeSharp.API/Generated/EngineFeatures/EngineFeature.g.cs"),
            output.ToString());
        Console.WriteLine($"Generated EngineFeature enum with {members.Count} Engine Features successfully.");
    }

    // "cssharp.game-rules/terminate-round" -> "GameRulesTerminateRound"
    private static string EngineFeatureMemberName(string name) =>
        string.Concat(name["cssharp.".Length..]
            .Split('.', '/', '-')
            .Select(part => char.ToUpperInvariant(part[0]) + part[1..]));

    // FNV-1a (32-bit) over the UTF-8 name.
    private static int EngineFeatureValue(string name)
    {
        var hash = 2166136261u;
        foreach (var b in Encoding.UTF8.GetBytes(name))
        {
            hash = unchecked((hash ^ b) * 16777619u);
        }

        return unchecked((int)hash);
    }
}
